const translations = { hi: hindi }

const LanguageContext = createContext(null)

const getInitialLanguage = () => {
  const saved = localStorage.getItem(LANGUAGE_KEY)
  if (saved === 'en' || saved === 'hi') return saved
  return navigator.language?.toLowerCase().startsWith('hi') ? 'hi' : 'en'
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage)

  useEffect(() => {
    localStorage.setItem(LANGUAGE_KEY, language)
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en'
    document.documentElement.dir = 'ltr'
  }, [language])

  const t = useCallback((text, values) => {
    if (typeof text !== 'string') return text
    let source = text
    let dynamicValues = {}
    if (language === 'hi') {
      let match = text.match(/^Good for (.+)$/)
      if (match) {
        source = 'Good for {interests}'
        dynamicValues.interests = match[1].split(', ').map((interest) => hindi[interest] || interest).join(', ')
      } else if ((match = text.match(/^Rain jacket territory: (\d+) of (\d+) days look wet\.$/))) {
        source = 'Rain jacket territory: {wet} of {total} days look wet.'
        dynamicValues = { wet: match[1], total: match[2] }
      } else if ((match = text.match(/^Mostly fine, though (\d+) days? might see rain\.$/))) {
        source = `Mostly fine, though {wet} ${match[1] === '1' ? 'day' : 'days'} might see rain.`
        dynamicValues.wet = match[1]
      } else if ((match = text.match(/^(\d+) nights? × (\d+) rooms?$/))) {
        source = `${match[1] === '1' ? '{nights} night × {rooms} room' : '{nights} nights × {rooms} rooms'}`
        dynamicValues = { nights: match[1], rooms: match[2] }
      } else if ((match = text.match(/^(\d+) days of meals for (\d+)$/))) {
        source = '{days} days of meals for {travelers}'
        dynamicValues = { days: match[1], travelers: match[2] }
      } else if ((match = text.match(/^(\d+) planned activities$/))) {
        source = '{count} planned activities'
        dynamicValues.count = match[1]
      } else if ((match = text.match(/^You're about (.+) ([A-Z]{3}) over your limit\.$/))) {
        source = "You're about {amount} {currency} over your limit."
        dynamicValues = { amount: match[1], currency: match[2] }
      } else if ((match = text.match(/^Manual costs and planned activity prices alone exceed your ceiling by about (.+) ([A-Z]{3})\.$/))) {
        source = 'Manual costs and planned activity prices alone exceed your ceiling by about {amount} {currency}.'
        dynamicValues = { amount: match[1], currency: match[2] }
      } else if ((match = text.match(/^Switching to (.+) travel style would save roughly (.+) ([A-Z]{3})\.$/))) {
        source = 'Switching to {style} travel style would save roughly {amount} {currency}.'
        dynamicValues = { style: hindi[match[1]] || match[1], amount: match[2], currency: match[3] }
      } else if ((match = text.match(/^You've got about (.+) ([A-Z]{3}) of headroom\.$/))) {
        source = "You've got about {amount} {currency} of headroom."
        dynamicValues = { amount: match[1], currency: match[2] }
      }
    }
    const translated = language === 'en' ? source : translations[language][source] || source
    const replacements = values ? { ...dynamicValues, ...values } : dynamicValues
    if (!Object.keys(replacements).length) return translated
    return translated.replace(/\{(\w+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(replacements, key) ? String(replacements[key]) : match
    ))
  }, [language])

  const value = useMemo(() => ({
    language,
    locale: language === 'hi' ? 'hi-IN' : 'en',
    setLanguage,
    t,
  }), [language, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside <LanguageProvider>')
  return context
}
